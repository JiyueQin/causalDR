#' Simulate left-truncated semi-competing risks data with treatment and confounding
#'
#' Generates semi-competing risks data subject to covariate-dependent left truncation
#' and right censoring, adapted from Zhang et al. (2024). In the population before
#' truncation:
#' \itemize{
#'   \item \eqn{U_1, U_2 \sim U(0, 1)} and \eqn{Z_j = U_1 + U_2 + \epsilon_j},
#'     \eqn{\epsilon_j \sim N(-1, 1)}, \eqn{j = 1, 2};
#'   \item \eqn{A \sim} Bernoulli with \eqn{\mathrm{logit}\{P(A = 1 \mid Z)\} = (1, Z_1, Z_2)^\top \alpha};
#'   \item with probability 1/2, \eqn{T_1^a = \infty} and
#'     \eqn{T_2^a = T_{\min} + \Lambda_0^{a,-1}\{-\log(U_1)/2\}}; otherwise
#'     \eqn{T_1^a = T_{\min} + \Lambda_0^{a,-1}\{-\log(U_1)/2\}} and
#'     \eqn{T_2^a = T_{\min} + \Lambda_0^{a,-1}\{-\log(U_2) + \Lambda_0^a(T_1^a - T_{\min})\}},
#'     where \eqn{T_{\min} \ge 0} is a location shift;
#'   \item the truncation time \eqn{Q} is independent of \eqn{(T_1, T_2)} given \eqn{(A, Z)}.
#' }
#' Subjects are retained if \eqn{Q < T = \min(T_1, T_2)}. The residual censoring time
#' \eqn{D \mid A \sim \mathrm{Exp}\{\exp(\gamma_0 + \gamma_1 A)\}}, and \eqn{C = Q + D}.
#'
#' Two truncation models are available.
#' \itemize{
#'   \item \code{Q_model = "uniform"} (default): the design of Wang et al., with
#'     \eqn{G(q \mid A, Z) = P(Q \le q \mid A, Z) = (q / q_{\max})^{\exp(\eta_0 + \eta_1 Z_1 + \eta_2 Z_2 + \eta_3 A)}}
#'     on \eqn{[0, q_{\max}]}, i.e., \eqn{q_{\max} - Q} follows a proportional hazards model
#'     with the baseline hazard of the uniform distribution on \eqn{[0, q_{\max}]}. Then
#'     \eqn{Q} is continuous and the Cox model on the reversed time scale used by
#'     \code{\link{causalAIPWtrunc}} is correctly specified. Since there is no point mass at
#'     0, positivity requires \code{T_min > 0}, which gives
#'     \eqn{G(T \mid A, Z) \ge (T_{\min} / q_{\max})^{\exp(\eta_0 + \eta_1 Z_1 + \eta_2 Z_2 + \eta_3 A)}}.
#'     The defaults follow Wang et al.: \eqn{\eta = (-0.6, 0.4, 0.2, 0.6)},
#'     \eqn{q_{\max} = 5} and \eqn{T_{\min} = 1}.
#'   \item \code{Q_model = "reverse_PH"}:
#'     \eqn{G(q \mid A, Z) = G_0(q)^{\exp(\eta_1 Z_1 + \eta_2 Z_2 + \eta_3 A)}}
#'     with \eqn{G_0(q) = p_0 + (1 - p_0) q / q_{\max}} on \eqn{[0, q_{\max}]}, i.e., a point
#'     mass at 0 and proportional reverse-time hazards. The point mass ensures
#'     \eqn{G(T \mid A, Z) \ge p_0^{\exp(\eta_1 Z_1 + \eta_2 Z_2 + \eta_3 A)} > 0}, so no shift of
#'     the event times is needed. The defaults are \eqn{\eta = (0.3, -0.3, 0.3)},
#'     \eqn{p_0 = 0.2}, \eqn{q_{\max} = 2} and \eqn{T_{\min} = 0}, which reproduce the data
#'     generated by earlier versions of this function.
#' }
#'
#' The true values of the estimands are available in closed form: for \eqn{t \ge T_{\min}},
#' \eqn{\mathrm{CIF}_1^a(t) = \mathrm{CIF}_2^a(t) = [1 - \exp\{-2\Lambda_0^a(t - T_{\min})\}]/2}
#' (and 0 for \eqn{t < T_{\min}}), and
#' \eqn{\mathrm{CIF}_3^a(t \mid t_1) = 1 - \exp\{\Lambda_0^a(t_1 - T_{\min}) - \Lambda_0^a(t - T_{\min})\}}
#' for \eqn{t > t_1 \ge T_{\min}}.
#'
#' @param n Integer scalar, the number of retained (observed) subjects.
#' @param alpha Numeric vector of length 3, the coefficients
#'   \eqn{(\alpha_0, \alpha_1, \alpha_2)} of the propensity score model.
#' @param Lambda0 List of two vectorized functions, the baseline cumulative hazards
#'   \eqn{\Lambda_0^a} for \eqn{a = 0, 1}.
#' @param Lambda0_inv List of two vectorized functions, the inverses of the functions
#'   in \code{Lambda0}.
#' @param Q_model Character scalar, \code{"uniform"} (default) or \code{"reverse_PH"}.
#' @param eta Numeric vector, the coefficients of the truncation model:
#'   \eqn{(\eta_0, \eta_1, \eta_2, \eta_3)} for \code{"uniform"}, multiplying
#'   \eqn{(1, Z_1, Z_2, A)}, and \eqn{(\eta_1, \eta_2, \eta_3)} for
#'   \code{"reverse_PH"}, multiplying \eqn{(Z_1, Z_2, A)}. If \code{NULL}, the default
#'   of the chosen \code{Q_model} is used.
#' @param p0 Numeric scalar in \eqn{[0, 1)}, the point mass at 0 of \eqn{G_0} for
#'   \code{"reverse_PH"}; ignored for \code{"uniform"}.
#' @param q_max Positive numeric scalar, the upper limit of the support of \eqn{Q}; if
#'   \code{NULL}, 5 for \code{"uniform"} and 2 for \code{"reverse_PH"}.
#' @param gamma Numeric vector of length 2, the coefficients
#'   \eqn{(\gamma_0, \gamma_1)} of the residual censoring model.
#' @param T_min Nonnegative numeric scalar, the location shift of the event times, so
#'   that \eqn{T_1, T_2 \ge T_{\min}} and the transition hazards are 0 on
#'   \eqn{[0, T_{\min})}; if \code{NULL}, 1 for \code{"uniform"} and 0 for
#'   \code{"reverse_PH"}.
#'
#' @return A list with components
#' \describe{
#'   \item{\code{dat}}{The observed data: a tibble with \code{n} rows and columns
#'     \code{id}, \code{A}, \code{Q}, \code{X1}, \code{X2}, \code{delta1}, \code{delta2},
#'     \code{Z1}, \code{Z2} and \code{event_type}.}
#'   \item{\code{dat_full}}{The full data before truncation and censoring, for use with
#'     \code{\link{full_data_est_trunc}}: a tibble with all generated subjects up to the
#'     \code{n}-th retained one, i.e., the population sample from which \code{dat} was
#'     drawn, with columns \code{id_full}, \code{A}, \code{Q}, \code{Z1}, \code{Z2}, the
#'     potential outcomes \code{T1_0}, \code{T2_0}, \code{T1_1}, \code{T2_1}, the logical
#'     \code{observed} (\eqn{Q < T}) and \code{id} (the row id in \code{dat}, or
#'     \code{NA} if truncated).}
#'   \item{\code{prop_truncated}}{Numeric scalar, the proportion of generated subjects
#'     that were truncated.}
#' }
#'
#' @examples
#' # continuous truncation time as in Wang et al., with event times shifted by 1
#' sim = sim_data_trunc(n = 300)
#' head(sim$dat)
#' head(sim$dat_full)
#' sim$prop_truncated
#'
#' # point mass of the truncation time at 0, without shifting the event times
#' sim = sim_data_trunc(n = 300, Q_model = 'reverse_PH')
#' mean(sim$dat$Q == 0)
#' @export
sim_data_trunc = function(n = 500,
                          alpha = c(0, 1.5, -1.5),
                          Lambda0 = list(function(t) 0.2*t, function(t) 0.3*t),
                          Lambda0_inv = list(function(u) u/0.2, function(u) u/0.3),
                          Q_model = 'uniform',
                          eta = NULL,
                          p0 = 0.2, q_max = NULL,
                          gamma = c(log(0.1), 0.3),
                          T_min = NULL){
  if (length(Q_model) != 1 || !Q_model %in% c('uniform', 'reverse_PH')) {
    stop('Q_model should be one of the following: uniform, reverse_PH')
  }
  # defaults that depend on the truncation model
  is_uniform = Q_model == 'uniform'
  if (is.null(eta)) eta = if (is_uniform) c(-0.6, 0.4, 0.2, 0.6) else c(0.3, -0.3, 0.3)
  if (is.null(q_max)) q_max = if (is_uniform) 5 else 2
  if (is.null(T_min)) T_min = if (is_uniform) 1 else 0
  if (length(eta) != 3 + is_uniform) stop('eta should have length ', 3 + is_uniform, ' for ', Q_model)
  if (Q_model == 'reverse_PH' && (p0 < 0 || p0 >= 1)) stop('p0 should be in [0, 1)')
  if (q_max <= 0) stop('q_max should be positive')
  if (T_min < 0) stop('T_min should be nonnegative')

  gen_population = function(N){
    U1 = runif(N)
    U2 = runif(N)
    Z1 = U1 + U2 + rnorm(N, -1, 1)
    Z2 = U1 + U2 + rnorm(N, -1, 1)
    A = rbinom(N, 1, inv.logit(alpha[1] + alpha[2]*Z1 + alpha[3]*Z2))
    no_illness = rbinom(N, 1, 0.5) == 1
    T_a = map(1:2, function(j){
      T1 = Lambda0_inv[[j]](-log(U1)/2)
      T2 = ifelse(no_illness, T1, Lambda0_inv[[j]](-log(U2) + Lambda0[[j]](T1)))
      T1[no_illness] = Inf
      list(T1 = T_min + T1, T2 = T_min + T2)
    })
    T1 = ifelse(A == 1, T_a[[2]]$T1, T_a[[1]]$T1)
    T2 = ifelse(A == 1, T_a[[2]]$T2, T_a[[1]]$T2)

    if (is_uniform) {
      # G(Q | A, Z) = V with V ~ U(0, 1), where G_0(q) = q/q_max, i.e., Q = q_max V^{exp(-lp)}
      lp = eta[1] + eta[2]*Z1 + eta[3]*Z2 + eta[4]*A
      Q = q_max*runif(N)^exp(-lp)
    } else {
      # G(Q | A, Z) = V with V ~ U(0, 1), i.e., G_0(Q) = V^{exp(-lp)}
      lp = eta[1]*Z1 + eta[2]*Z2 + eta[3]*A
      G0_Q = runif(N)^exp(-lp)
      Q = ifelse(G0_Q <= p0, 0, q_max*(G0_Q - p0)/(1 - p0))
    }
    tibble(A, Q, T1, T2, Z1, Z2,
           T1_0 = T_a[[1]]$T1, T2_0 = T_a[[1]]$T2, T1_1 = T_a[[2]]$T1, T2_1 = T_a[[2]]$T2)
  }

  pop_ls = list()
  n_kept = 0
  while (n_kept < n) {
    pop = gen_population(2*n)
    pop_ls[[length(pop_ls) + 1]] = pop
    n_kept = n_kept + sum(pop$Q < pmin(pop$T1, pop$T2))
  }
  pop = bind_rows(pop_ls)
  kept_idx = which(pop$Q < pmin(pop$T1, pop$T2))
  prop_truncated = 1 - length(kept_idx)/nrow(pop)
  dat = pop[kept_idx[1:n], ]

  # full data: all generated subjects up to the n-th retained one
  dat_full = pop[1:kept_idx[n], c('A', 'Q', 'Z1', 'Z2', 'T1_0', 'T2_0', 'T1_1', 'T2_1')]
  observed = seq_len(kept_idx[n]) %in% kept_idx
  dat_full = tibble(id_full = seq_len(kept_idx[n]), dat_full, observed = observed,
                    id = ifelse(observed, cumsum(observed), NA_integer_))

  D = rexp(n, rate = exp(gamma[1] + gamma[2]*dat$A))
  dat = dat %>%
    mutate(C = Q + D,
           X1 = pmin(T1, T2, C),
           X2 = pmin(T2, C),
           delta1 = 1*(T1 <= pmin(T2, C)),
           delta2 = 1*(T2 <= C),
           id = 1:n) %>%
    get_event_type() %>%
    select(id, A, Q, X1, X2, delta1, delta2, Z1, Z2, event_type)
  list(dat = dat, dat_full = dat_full, prop_truncated = prop_truncated)
}
